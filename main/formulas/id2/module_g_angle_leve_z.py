import math


def solve_g(data):
    # ===============================
    # 輸入端（圖面角度）
    # ===============================
    r  = float(data["刀鼻半徑"]) 
    A  = float(data["角度2"])


    # ===============================
    # 角度鎖定
    # ===============================
    if A <= 0 or A >= 90:
        raise ValueError("角度 A 必須介於 0 ~ 90 度")

    # ===============================
    # 計算（終點端 Z，反邊修正後）
    # ===============================
    z_offset = r * math.tan(math.radians(A / 2))
    G01=z_offset
    # ===============================
    # 輸出
    # ===============================



    def _fmt(x):
    # 例如固定顯示到小數點兩位
        return f"{x:.3f}"
    
    result_values = {
        "G01": G01,
          
     }

    text_lines = [
        "➡️ 前端斜角 → 平線 → 終點弧（C 工廠）",
        f"G01 = {_fmt(G01)}",
        
      
    ]

    return {
        "ok": True,
        "text_lines": text_lines,
        "values": result_values,
    }


# -------------------------------------------------------
# 🔁 對外統一介面
# -------------------------------------------------------
def solve(data: dict):
    return solve_g(data)
