import math

# -------------------------------------------------------
# 🧠 核心計算（D 工廠）
# -------------------------------------------------------
def solve_d(data):
    A_values = data.get("A", {})
    B51 = A_values.get("B51")
  
    # ===================================================
    # 1️⃣ 讀取並整理輸入（對齊 Excel B 欄）
    # ===================================================
    B2  = float(B51)   #起始點X直徑
    B3  = float(data["角度2"])
    B4  = float(data["未端D"]) /2   
    B5  = float(data["未端R"])    
    B6  = float(data["刀鼻半徑"]) *2
    B7  = float(data["前端w"])
    B8  = 0.0         


    # === 基本量 ===
    B10 = -math.tan(math.radians(B3))
    B11 = B2 - B10 * B8
    B12 = math.sqrt(1.0 + B10**2)

    B13 = B6 / 2.0
    B14 = B5 + B13
    B16 = B4 - B5

    # === 第一個圓與直線交會（決定 B28,B29）===
    # 直線：X = B10*Z + B11
    # 圓心：(B16, B17) 半徑 B5
    B17 = (B16 - B11 + B5*B12) / B10

    B20 = 1.0 + B10**2
    B21 = 2.0 * ( B10*(B11 - B16) - B17 )
    B22 = B17**2 + (B11 - B16)**2 - B5**2
    B23 = B21**2 - 4.0*B20*B22
    # 兩根
    sqrt_B23 = math.sqrt(max(0.0, B23))
    B24 = (-B21 - sqrt_B23) / (2.0*B20)
    B25 = (-B21 + sqrt_B23) / (2.0*B20)
    B26 = B10 * B24 + B11
    B27 = B10 * B25 + B11
    # 依 Excel：B28,B29 用 IF 選較小的 Z 根及對應 X
    if B24 < B25:
        B28, B29 = B24, B26
    else:
        B28, B29 = B25, B27

    # === 第二個圓（半徑換成 B14）與同一直線交會（B37..B40）===
    B32 = B11 + B13 * B12        # 平移後的截距
    B33 = 1.0 + B10**2
    B34 = 2.0 * ( B10*(B32 - B16) - B17 )
    B35 = B17**2 + (B32 - B16)**2 - B14**2
    B36 = B34**2 - 4.0*B33*B35
    sqrt_B36 = math.sqrt(max(0.0, B36))
    # 兩根
    B37 = (-B34 - sqrt_B36) / (2.0*B33)
    B38 = (-B34 + sqrt_B36) / (2.0*B33)
    B39 = B10 * B37 + B32
    B40 = B10 * B38 + B32

    # === E2, E3（等價 Excel 的 B41, B42）===
    # B41 = IF( (B37-B28)^2+(B39-B29)^2 <= (B38-B28)^2+(B40-B29)^2, B37, B38 )
    d1 = (B37 - B28)**2 + (B39 - B29)**2
    d2 = (B38 - B28)**2 + (B40 - B29)**2
    B41 = B37 if d1 <= d2 else B38
    # B42 = IF(B41=B37, B39, B40)
    B42 = B39 if (abs(B41 - B37) < 1e-12) else B40

    # === E5（=B45）、E4（=B46）===
    B45 = B4 + B13
    # B46 = B17 - sqrt( max(0, B14^2 - (B45 - B16)^2 ) )
    inside = max(0.0, B14**2 - (B45 - B16)**2)
    B46 = B17 - math.sqrt(inside)
    D51 = B41-B7-B13
    B52= (B42-B13)*2
    B53= (B45-B13)*2
    B54=  B46-B7-B13
    B55=  B5+B13


    def _fmt(x):
     # 例如固定顯示到小數點兩位
        return f"{x:.3f}"

    result_values = {
        "D51": D51,
        "B52": B52,
        "B53": B53,
        "B54": B54,
        "B55": B55,
        
    }

    text_lines = [
        "➡️ 前端斜角 → 平線 → 終點弧（D 工廠）",
        f"D51 = {_fmt(D51)}",
        f"B52 = {_fmt(B52)}",
        f"B53 = {_fmt(B53)}",
        f"B54 = {_fmt(B54)}",
        f"B55 = {_fmt(B55)}",
    ]

    return {
        "ok": True,
        "text_lines": text_lines,
        "values": result_values,
    }


# -------------------------------------------------------
# 🔁 對外統一介面
# -------------------------------------------------------
def solve(data: dict):
    return solve_d(data)       