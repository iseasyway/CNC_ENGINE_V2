import math


def solve_c_1(data):


    # ==================================================
    # 1️⃣ 讀取並整理輸入（對齊 Excel B 系列）
    # --------------------------------------------------
    # 說明：
    # - 所有輸入皆轉為 float
    # - 外徑一律轉為半徑計算
    # ==================================================
    theta_deg  = float(data["角度1"]) 
    r  = float(data["刀鼻半徑"])

   

    theta = math.radians(theta_deg)

    X = r * math.sin(theta)
    Z = r * math.cos(theta)

    def _fmt(x):
    # 例如固定顯示到小數點兩位
        return f"{x:.3f}"
    C51=X
    C52=Z
    result_values = {
        "C51": C51,
        "C52": C52,
  
     }

    text_lines = [
        "➡️ 前端斜角 → 平線 → 終點弧（C 工廠）",
        f"C51 = {_fmt(C51)}",
        f"C52 = {_fmt(C52)}",
      
    ]

    return {
        "ok": True,
        "text_lines": text_lines,
        "values": result_values,
    }


# -------------------------------------------------------
# 🔁 對外統一介面
# -------------------------------------------------------
def solve(data: dict):
    return solve_c_1(data)


