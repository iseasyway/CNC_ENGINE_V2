import math


def solve_a(data):


    # ==================================================
    # 1️⃣ 讀取並整理輸入（對齊 Excel B 系列）
    # --------------------------------------------------
    # 說明：
    # - 所有輸入皆轉為 float
    # - 外徑一律轉為半徑計算
    # ==================================================
    K1  = float(data["未端D"]) / 2.0
    K2  = float(data["角度2"])
    K3 =  float(data["角度1"])
    K4  = float(data["原點至終點面W"]) 
    K5  = float(data["前端w"])
   
    # 第一段的有效水平距離（藏在程式裡）
    W1_eff = K4 - K5    # 50 - 10 = 40

    # 第一段（角度1）
    DX1 = math.tan(math.radians(K2)) * W1_eff
    X_mid = K1 - DX1

    # 第二段（角度2）
    DX2 = math.tan(math.radians(K3)) * K5
    X_right = X_mid - DX2
    B51=X_mid
    B52=X_right


    def _fmt(x):
    # 例如固定顯示到小數點兩位
        return f"{x:.3f}"
    
    result_values = {
        "B51": B51,
        "B52": B52,

   
     }

    text_lines = [
        "➡️ 前端斜角 → 平線 → 終點弧（C 工廠）",
        f"B51 = {_fmt(B51)}",
        f"B52 = {_fmt(B52)}",
      
    ]

    return {
        "ok": True,
        "text_lines": text_lines,
        "values": result_values,
    }


# -------------------------------------------------------
# 🔁 對外統一介面
# -------------------------------------------------------
def solve(data: dict):
    return solve_a(data)


