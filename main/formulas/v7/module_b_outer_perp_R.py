import math


def solve_b(data):

    A_values = data.get("A", {})
    B51 = A_values.get("B51")
    # ==================================================
    # 1️⃣ 讀取並整理輸入（對齊 Excel B 系列）
    # --------------------------------------------------
    # 說明：
    # - 所有輸入皆轉為 float
    # - 外徑一律轉為半徑計算
    # ==================================================
    B2  = float(B51)   # 小徑X
    B3  = -abs(float(data["前端w"]) )     # Z軸原點至圓孤起始距離
    B4_deg  = float(data["角度1"]) # 斜度角
    B5  = float(data["前端R"])
    B6  = float(data["刀鼻半徑"]) *2  # 刀鼻直徑
    
    
     # ===== 中間量（完全等價 Excel）=====
    # ---- 基本三角/幾何量 ----
    B9  = B6 / 2.0
    B10 = -1.0 / math.tan(math.radians(B4_deg))   # = -cot(θ)
    B11 = B3 - B10 * B2
    B12 = math.sqrt(1.0 + B10**2)

    # 兩條候選線對應的 X 截距（Excel：B13、B14）
    B13 = (-B11 - B5 + B5*B12) / B10
    B14 = (-B11 - B5 - B5*B12) / B10

    # B15 = MIN(B13, B14)  → B21 直接等於 B15
    B15 = min(B13, B14)

    # 其他中間量
    B16 = -B5
    B17 = (B15 + B10*(B16 - B11)) / (1.0 + B10**2)
    B18 = B10 * B17 + B11
    B25 = math.copysign(1.0, B16 - (B10*B15 + B11))  # SIGN(...)

    B26 = B11 - B25*B9*B12
    B27 = B5 + B9
    B28 = 1.0 + B10**2
    B29 = 2.0 * ( B10*(B26 - B16) - B15 )
    B30 = B15**2 + (B26 - B16)**2 - B27**2
    B31 = max(0.0, B29**2 - 4.0*B28*B30)

    # 根（B32,B33），及其對應點（B36..B39）
    sqrt_B31 = math.sqrt(B31)
    B32 = (-B29 + sqrt_B31) / (2.0*B28)
    B33 = (-B29 - sqrt_B31) / (2.0*B28)
    B34 = B10*B32 + B26
    B35 = B10*B33 + B26
    B36 = (B32 + B10*(B34 - B11)) / (1.0 + B10**2)
    B37 = B10*B36 + B11
    B38 = (B33 + B10*(B35 - B11)) / (1.0 + B10**2)
    B39 = B10*B38 + B11

    # 與圓心(B17,B18)距離（兩根比較用）
    B40 = math.hypot(B36 - B17, B37 - B18)
    B41 = math.hypot(B38 - B17, B39 - B18)

    # ---- 目標四格 ----
    # B21 = B15
    B21 = B15
    # B22 = B9
    B22 = B9

    # B42 = IF(B31=0, -B29/(2*B28), IF(B40<=B41, B32, B33))
    if B31 == 0:
        B42 = -B29 / (2.0*B28)
    else:
        B42 = B32 if (B40 <= B41) else B33

    # B43 = IF(B31=0, B10*B42 + B26, IF(B40<=B41, B34, B35))
    if B31 == 0:
        B43 = B10*B42 + B26
    else:
        B43 = B34 if (B40 <= B41) else B35

    B51=(B21-B9)*2
    B52=B22-B9
    B53=(B42-B9)*2
    B54=B43-B9
    B55=B5+B9


    def _fmt(x):
     # 例如固定顯示到小數點兩位
        return f"{x:.3f}"

 

    result_values = {
         "B51": B51,
         "B52": B52,
         "B53": B53,
         "B54": B54,
         "B55": B55,
      
     }

    text_lines = [
        "➡️ 前端斜角 → 平線 → 終點弧（C 工廠）",
        f"B51 = {_fmt(B51)}",
        f"B52 = {_fmt(B52)}",
        f"B53 = {_fmt(B53)}",
        f"B54 = {_fmt(B54)}",
        f"B55 = {_fmt(B55)}",
      
    ]

    return {
        "ok": True,
        "text_lines": text_lines,
        "values": result_values,
    }


# -------------------------------------------------------
# 🔁 對外統一介面
# -------------------------------------------------------
def solve(data: dict):
    return solve_b(data)