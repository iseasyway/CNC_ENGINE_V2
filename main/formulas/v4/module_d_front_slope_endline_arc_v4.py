# -*- coding: utf-8 -*-

import math


# -------------------------------------------------------
# 🔧 顯示用格式化工具
# -------------------------------------------------------
def _fmt(x, p=6):
    """
    數值顯示格式化
    - 預設小數點後 6 位
    - None 則顯示為 "-"
    """
    return f"{x:.{p}f}" if x is not None else "-"


# -------------------------------------------------------
# 🧠 核心計算（C 工廠）
# -------------------------------------------------------
def solve_d(data):

    # ===================================================
    # 1️⃣ 讀取並整理輸入（對齊 Excel B 欄）
    # ===================================================
    K1 = float(data["終點x軸外徑"])/2         # 小徑 X（A 工廠）
    
    K2 = float(data.get("斜度長W2", 999))           # Z_A
    K3 = float(data["前端x軸外徑"])/2       # X_B（半徑）
    K4 = float(data["斜度角"])               # 角度（deg）
    K5 = float(data["刀鼻半徑"])          # 刀鼻直徑
    K6 = float(data["z軸長度"])          
    # ===================================================
    # 2️⃣ 輔助函式：判斷是否為空值
    # ===================================================
    def is_blank(v):
        return v in (None, "", 999, -999)

    # ===================================================
    # 3️⃣ 輸入狀態判斷
    # ===================================================
    
    has_ZA = not is_blank(K2)
    has_XB = not is_blank(K3)

    if not has_ZA and not has_XB:
        raise ValueError("❌ K2(Z_A) 與 K3(X_B) 至少需輸入一個")

    if has_ZA and has_XB:
        raise ValueError("❌ K2(Z_A) 與 K3(X_B) 只能輸入一個")

    # ===================================================
    # 4️⃣ 基準與角度
    # ===================================================

          
    X_A = K1
    r = K5
    theta = K4

    theta_eff = 90.0 - theta
    tt = math.tan(math.radians(theta_eff))

    # ===================================================
    # 5️⃣ 補算 Z_A
    # ===================================================
    if has_ZA:
        # 模式 A：直接用 Z
        Z_A = float(K2)
        src = "使用 K2(Z_A)"

    else:
        # 模式 B：由 X 反推 Z
        X_B = float(K3)
        Z_A = -abs(X_A - X_B) * tt
        src = "使用 K3(X_B) → 反推 Z_A"

        # --- 角度轉換 ---
        theta_eff = 90.0 - theta
        th = math.radians(theta_eff)

        tt = math.tan(th)
        st = math.sin(th)
        ct = math.cos(th)

        # --- B 點 ---
        X_B = X_A - abs(Z_A) / tt
        Z_B = 0.0

        # --- 圓心①：Z=0 ---
        E2_Z = r
        E2_X = X_B + (r - (E2_Z - Z_B) * ct) / st

        # --- 圓心②：X=X_A ---
        E4_X = X_A + r
        E4_Z = Z_A + (r - (E4_X - X_A) * st) / ct
        D43 = (E4_X-K5)*2
        D44 = (E4_Z-K6)-K5
    # ===================================================
    # 6️⃣ 統一輸出
    # ===================================================
    result_values = {
        "D41": E2_X,
        "D42": E2_Z,
        "D43": D43,
        "D44": D44,
    }

    text_lines = [
        "➡️ 前端斜角 → 平線 → 終點弧（C 工廠）",
        f"D41 = {_fmt(E2_X)}",
        f"D42 = {_fmt(E2_Z)}",
        f"D43 = {_fmt(E4_X)}",
        f"D44 = {_fmt(E4_Z)}",
    ]

    return {
        "ok": True,
        "text_lines": text_lines,
        "values": result_values,
    }


# -------------------------------------------------------
# 🔁 對外統一介面
# -------------------------------------------------------
def solve(data: dict):
    return solve_d(data)

