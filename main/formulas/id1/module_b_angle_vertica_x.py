import math


def solve_b(data):
    # ===============================
    # 輸入端（圖面角度）
    # ===============================
    r  = float(data["刀鼻半徑"]) 
    A  = float(data["角度"])


    # ===============================
    # 角度鎖定（核心）
    # ===============================
    if A <= 0 or A >= 90:
        raise ValueError("角度 A 必須大於 0 度且小於 90 度")

    # ===============================
    # 計算（固定公式，不玩花樣）
    # ===============================
    offset = r * math.tan(math.radians((90 - A) / 2))

    C02=offset




    def _fmt(x):
    # 例如固定顯示到小數點兩位
        return f"{x:.3f}"
    
    result_values = {
        "C02": C02,
          
     }

    text_lines = [
        "➡️ 前端斜角 → 平線 → 終點弧（C 工廠）",
        f"C02 = {_fmt(C02)}",
        
      
    ]

    return {
        "ok": True,
        "text_lines": text_lines,
        "values": result_values,
    }


# -------------------------------------------------------
# 🔁 對外統一介面
# -------------------------------------------------------
def solve(data: dict):
    return solve_b(data)
